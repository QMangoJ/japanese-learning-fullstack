// 9章 運動・リゾート・いなか (textbook pp. 199–214), transcribed from Daniel's photos.
// Reading answers and writing answers follow the printed exercise, not handwritten notes.
// The 草・原 page number (206) is inferred: its photo shows no printed number, but the
// page faces 湖・谷 (207) in the book, right after 自・然 (205).
type SourceQuestion = readonly [page: number, prompt: string, target: string, answer: string, accepted?: string[]];

function makeLesson(
	id: string,
	title: string,
	pages: number[],
	kanji: string[],
	reading: SourceQuestion[],
	writing: SourceQuestion[],
): KanjiExamLesson {
	const make = (kind: KanjiExamQuestionKind, rows: SourceQuestion[]) =>
		rows.map(([page, prompt, target, answer, accepted], index) => ({
			id: `${id}-${kind}-${page}-${index + 1}`,
			lessonId: id,
			page,
			kind,
			prompt,
			target,
			answer,
			accepted,
		}));
	return { id, title, pages, kanji, questions: [...make("reading", reading), ...make("writing", writing)] };
}

