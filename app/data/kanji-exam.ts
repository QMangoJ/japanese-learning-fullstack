export function shuffleKanjiExamQuestions<T>(questions: readonly T[], random: () => number = Math.random): T[] {
	const shuffled = [...questions];
	for (let index = shuffled.length - 1; index > 0; index -= 1) {
		const target = Math.floor(random() * (index + 1));
		[shuffled[index], shuffled[target]] = [shuffled[target], shuffled[index]];
	}
	return shuffled;
}

export function questionsForMode(batch: KanjiExamBatch, mode: KanjiExamMode): KanjiExamQuestion[] {
	const questions = batch.lessons.flatMap((lesson) => lesson.questions);
	return mode === "mixed" ? questions : questions.filter((question) => question.kind === mode);
}

function katakanaToHiragana(value: string) {
	return value.replace(/[ァ-ヶ]/g, (char) => String.fromCharCode(char.charCodeAt(0) - 0x60));
}

export function normalizeKanjiExamAnswer(value: string, kind: KanjiExamQuestionKind): string {
	const normalized = value.normalize("NFKC").replace(/[\s　。、，,.・]/g, "").trim();
	return kind === "reading" ? katakanaToHiragana(normalized) : normalized;
}

export function isKanjiExamAnswerCorrect(question: KanjiExamQuestion, value: string): boolean {
	const answer = normalizeKanjiExamAnswer(value, question.kind);
	return [question.answer, ...(question.accepted || [])].some(
		(candidate) => normalizeKanjiExamAnswer(candidate, question.kind) === answer,
	);
}
