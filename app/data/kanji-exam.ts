export type KanjiExamMode = "reading" | "writing" | "mixed";

export type KanjiExamQuestionKind = Exclude<KanjiExamMode, "mixed">;

export type KanjiExamQuestion = {
	id: string;
	lessonId: string;
	page: number;
	kind: KanjiExamQuestionKind;
	prompt: string;
	target: string;
	answer: string;
	accepted?: string[];
};

export type KanjiExamLesson = {
	id: string;
	title: string;
	pages: number[];
	kanji: string[];
	questions: KanjiExamQuestion[];
};

export type KanjiExamBatch = {
	id: string;
	title: string;
	subtitle: string;
	importedAt: string;
	source: "manual-photo-review" | "vision-api";
	lessons: KanjiExamLesson[];
};

type SourceQuestion = readonly [page: number, prompt: string, target: string, answer: string, accepted?: string[]];

function makeLesson(
	id: string,
	title: string,
	pages: number[],
	kanji: string[],
	reading: SourceQuestion[],
	writing: SourceQuestion[],
): KanjiExamLesson {
	const make = (kind: KanjiExamQuestionKind, rows: SourceQuestion[]) =>
		rows.map(([page, prompt, target, answer, accepted], index) => ({
			id: `${id}-${kind}-${page}-${index + 1}`,
			lessonId: id,
			page,
			kind,
			prompt,
			target,
			answer,
			accepted,
		}));
	return { id, title, pages, kanji, questions: [...make("reading", reading), ...make("writing", writing)] };
}

