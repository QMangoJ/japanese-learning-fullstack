export function buildN2GrammarContrast(grammar: any) {
	const getPoint = ([week, day, point]: PointRef) =>
		grammar?.weeks?.find((item: any) => item.n === week)?.days?.find((item: any) => item.day === day)?.points?.[point];

	return {
		intro: "把 N2 语法中功能相近、接续相似、考试时最容易混淆的句型按家族横向整理。标注如 3-2 可跳到第3周第2日的完整讲解；也可以切换到“每周总结”复习全部课程。",
		groups: groups.map((group) => ({
			title: group.title,
			tip: group.tip,
			rows: group.refs.map((ref) => {
				const point = getPoint(ref);
				if (!point) throw new Error(`Missing N2 grammar contrast point: ${ref.join("-")}`);
				const [week, day, pointIndex] = ref;
				const example = point.examples?.[0];
				return {
					loc: `${week}-${day}`,
					locHash: `#/day/${week}-${day}/p${pointIndex}`,
					form: point.connection || point.pattern,
					mean: point.usage_cn,
					eg: example?.jp || point.pattern,
					eg_r: example?.jp_r,
					eg_cn: example?.cn,
				};
			}),
			quiz: {
				title: "辨析练习",
				items: group.quiz.map(({ answer: _answer, ...item }, index) => ({ ...item, n: index + 1 })),
				answers: group.quiz.map((item, index) => `${circled[index]}${item.answer}`).join(" "),
			},
		})),
	};
}

export const n2GrammarContrastGroupCount = groups.length;
