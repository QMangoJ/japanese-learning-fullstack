type Slice = { label: string; value: number; tone: number };

/** Redraws one of the printed pie charts. `tone` 0–1 picks the fill darkness. */
function pie(title: string, slices: Slice[]): string {
	const cx = 90;
	const cy = 92;
	const r = 74;
	let angle = -Math.PI / 2;
	const total = slices.reduce((sum, slice) => sum + slice.value, 0);

	const paths = slices
		.map((slice) => {
			const sweep = (slice.value / total) * Math.PI * 2;
			const x1 = cx + r * Math.cos(angle);
			const y1 = cy + r * Math.sin(angle);
			angle += sweep;
			const x2 = cx + r * Math.cos(angle);
			const y2 = cy + r * Math.sin(angle);
			const large = sweep > Math.PI ? 1 : 0;
			const fill = `color-mix(in srgb, currentColor ${Math.round(slice.tone * 100)}%, transparent)`;
			return `<path d="M${cx} ${cy} L${x1.toFixed(1)} ${y1.toFixed(1)} A${r} ${r} 0 ${large} 1 ${x2.toFixed(1)} ${y2.toFixed(1)} Z" fill="${fill}" stroke="currentColor" stroke-width="1"/>`;
		})
		.join("\n    ");

	const legend = slices
		.map((slice, index) => {
			const y = 24 + index * 17;
			const fill = `color-mix(in srgb, currentColor ${Math.round(slice.tone * 100)}%, transparent)`;
			return `<rect x="190" y="${y - 8}" width="11" height="11" fill="${fill}" stroke="currentColor" stroke-width="0.8"/>
    <text x="207" y="${y + 1}" font-size="9">${slice.label}　${slice.value}％</text>`;
		})
		.join("\n    ");

	return `<svg viewBox="0 0 420 200" role="img" aria-label="${title}の円グラフ">
    ${paths}
    <text x="${cx}" y="184" text-anchor="middle" font-size="13" font-weight="700">${title}</text>
    ${legend}
</svg>`;
}

