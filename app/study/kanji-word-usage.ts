function cleanSurface(jp: string) {
	return jp.replace(/[（(][^）)]*[）)]/g, "").trim();
}

export function getKanjiWordUsage(word: KanjiWord): KanjiWordUsage {
	const surface = cleanSurface(word.jp);
	if (VERB_FRAMES[surface]) return { posCn: "动词", posEn: "Verb", before: VERB_FRAMES[surface][0], after: VERB_FRAMES[surface][1] };
	if (I_ADJECTIVE_FRAMES[surface]) return { posCn: "い形容词", posEn: "い-adjective", before: I_ADJECTIVE_FRAMES[surface][0], after: I_ADJECTIVE_FRAMES[surface][1] };
	if (word.jp.includes("(な)") || word.jp.includes("（な）")) return { posCn: "な形容词", posEn: "な-adjective", before: "これはとても", after: "です。" };
	if (ADVERB_FRAMES[word.jp]) return {
		posCn: "副词",
		posEn: "Adverb",
		before: ADVERB_FRAMES[word.jp][0],
		after: ADVERB_FRAMES[word.jp][1],
		focus: word.jp === "必死(に)" ? "必死に" : surface,
		focusReading: word.jp === "必死(に)" ? "ひっしに" : word.reading,
	};
	if (EXPRESSIONS[word.jp]) {
		const focus = EXPRESSION_FOCUS[word.jp];
		return {
			posCn: "表达",
			posEn: "Expression",
			before: EXPRESSIONS[word.jp][0],
			after: EXPRESSIONS[word.jp][1],
			focus: focus?.[0],
			focusReading: focus?.[1],
		};
	}
	if (NOUN_FRAMES[surface]) return { posCn: "名词", posEn: "Noun", before: NOUN_FRAMES[surface][0], after: NOUN_FRAMES[surface][1] };
	if (PLACE_WORDS.has(surface)) return { posCn: "名词", posEn: "Noun", before: "これから", after: "へいきます。" };
	if (PERSON_WORDS.has(surface)) return { posCn: "名词", posEn: "Noun", before: "くわしいことは", after: "にききます。" };
	if (EVENT_OR_TIME_WORDS.has(surface)) return { posCn: "名词", posEn: "Noun", before: "つぎの", after: "はいつですか。" };
	if (NATURE_OR_RISK_WORDS.has(surface)) return { posCn: "名词", posEn: "Noun", before: "", after: "にちゅういしてください。" };
	if (THING_WORDS.has(surface)) return { posCn: "名词", posEn: "Noun", before: "この", after: "をつかいます。" };
	return { posCn: "名词", posEn: "Noun", before: "", after: "についてしらべます。" };
}

export function kanjiWordSurface(word: KanjiWord) {
	return cleanSurface(word.jp);
}
