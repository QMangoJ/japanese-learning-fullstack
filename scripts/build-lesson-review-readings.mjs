const dict = new Map();

function toHiragana(text) {
	return String(text).replace(/[\u30a1-\u30f6]/g, (ch) => String.fromCharCode(ch.charCodeAt(0) - 0x60));
}

function add(jp, reading, overwrite = false) {
	if (!jp || !reading) return;
	const core = String(jp)
		.replace(/[（(][^）)]*[）)]?/g, "")
		.replace(/[\/／].*$/, "")
		.replace(/\(.*?\)/g, "")
		.replace(/[？！、。]/g, "")
		.trim();
	if (!KANJI_RE.test(core) || core.length < 1 || core.length > 16) return;
	const kana = toHiragana(String(reading).replace(/<[^>]+>/g, "").replace(/[\s・]+/g, "").trim());
	if (!KANA_RE.test(kana)) return;
	if (overwrite || !dict.has(core)) dict.set(core, kana);
}

function isIchidan(surface, reading) {
	if (!surface.endsWith("る") || !reading.endsWith("る")) return false;
	if (GODAN_ERU_IRU.has(surface)) return false;
	const mora = reading.slice(-2, -1);
	return "いきぎしじちぢにひびみりけげせぜてでねへべめれえ".includes(mora);
}

function expandIAdj(surface, reading) {
	if (!surface.endsWith("い") || !reading.endsWith("い")) return;
	if (/(たい|ない|らしい)$/.test(surface)) return;
	const s = surface.slice(0, -1);
	const r = reading.slice(0, -1);
	for (const [form, kana] of [
		[s + "く", r + "く"],
		[s + "くて", r + "くて"],
		[s + "かった", r + "かった"],
		[s + "くない", r + "くない"],
		[s + "ければ", r + "ければ"],
		[s + "すぎ", r + "すぎ"],
		[s + "すぎた", r + "すぎた"],
		[s + "すぎない", r + "すぎない"],
		[s + "さ", r + "さ"],
	])
		putIfNew(form, kana);
}

function putIfNew(surface, reading) {
	if (!surface || !reading || !KANJI_RE.test(surface) || surface.length > 16) return;
	if (!dict.has(surface)) dict.set(surface, reading);
}

