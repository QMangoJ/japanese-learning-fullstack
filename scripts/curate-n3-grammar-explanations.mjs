for (let week = 1; week <= 6; week += 1) {
  const weekKey = `w${week}`;
  const answerGroup = grammar.besatsu[weekKey];
  const day = grammar.weeks[week - 1].days.find((item) => item.day === 7);

  for (const section of ["mondai1", "mondai2", "mondai3"]) {
    const itemByNumber = new Map(day[section].items.map((item) => [item.n, item]));
    const answerByNumber = new Map(answerGroup[section].map((item) => [item.n, item]));

    for (const entry of data[weekKey][section]) {
      const key = `${weekKey}-${section}-${entry.n}`;
      const item = itemByNumber.get(entry.n);
      const sourceAnswer = answerByNumber.get(entry.n);

      if (questionTranslations[key]) entry.trans = questionTranslations[key];

      // Weeks 5 and 6 already contain carefully authored Chinese explanations
      // in the source book data. Keep those instead of machine-generated text.
      if (week >= 5) {
        for (const field of ["trans", "why", "point", "link", "words"]) {
          if (sourceAnswer[field]) entry[field] = sourceAnswer[field];
        }
      }

      entry.option_translations = (item.opts || []).map(
        (option, index) => optionTranslations[option] || entry.option_translations?.[index] || "",
      );

      // Week 1 question 14 has a sentence-specific contrast between transitive
      // and intransitive verbs. Its hand-written explanation is more precise.
      if (!(week === 1 && section === "mondai1" && entry.n === 14) && week <= 4) {
        const correct = sourceAnswer.ans || 1;
        entry.why = (item.opts || []).map((option, index) => {
          const gloss = entry.option_translations[index];
          if (index + 1 === correct) {
            const answerNote = sourceAnswer.note ? `完整答案是「${sourceAnswer.note}」。` : "";
            return `「${option}」表示“${gloss}”。${answerNote}接续和句意都成立。`;
          }
          return `「${option}」表示“${gloss}”。放入本句后，接续、活用形式或语义不符合题意。`;
        });
      }

      entry.words = (entry.words || []).map((word) => ({
        ...word,
        kana: wordReadings[word.jp] || word.kana,
        cn: wordTranslations[word.jp] || word.cn,
      }));
    }
  }
}

