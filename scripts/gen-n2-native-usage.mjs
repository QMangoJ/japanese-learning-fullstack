// Generates app/data/n2-native-usage.ts from the per-day usage ratings already
// authored in app/data/n2-daily-summaries.ts (rows are ordered exactly like the
// lesson points; alignment is asserted by tests/unit/n2-grammar-summary.test.tsx).
// Codes: e=everyday （口语·很常用） c=common （日常·常用） s=situational （特定场景常用） f=formal （偏正式/书面）
// Run: node scripts/gen-n2-native-usage.mjs
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { N2_DAILY_SUMMARIES } from "../app/data/n2-daily-summaries.ts";

const jsonName = readdirSync("public/data").find((f) => /^n2grammar\..*\.json$/.test(f));
const book = JSON.parse(readFileSync(`public/data/${jsonName}`, "utf8"));
const CODE = { everyday: "e", common: "c", situational: "s", formal: "f" };
const out = {};
const dist = { e: 0, c: 0, s: 0, f: 0 };
for (const w of book.weeks) {
	for (const day of w.days) {
		if (!day.points) continue;
		const key = `${day.week}-${day.day}`;
		const summary = N2_DAILY_SUMMARIES[key];
		if (!summary) throw new Error(`no summary for ${key}`);
		if (summary.rows.length !== day.points.length)
			throw new Error(`${key}: rows ${summary.rows.length} != points ${day.points.length}`);
		out[key] = summary.rows.map((r) => { const c = CODE[r.usage]; dist[c]++; return c; }).join("");
	}
}
const body = `// GENERATED by scripts/gen-n2-native-usage.mjs — do not edit by hand.
// Source: the usage rating of each N2 grammar point in app/data/n2-daily-summaries.ts
// (rows ordered exactly like the lesson points of that day).
// Codes: e = everyday （口语 · 很常用）, c = common （日常 · 常用）,
//        s = situational （特定场景常用）, f = formal （偏正式／书面）.
export const N2_NATIVE_USAGE: Record<string, string> = ${JSON.stringify(out, null, "\t")};
`;
writeFileSync("app/data/n2-native-usage.ts", body);
console.log("days:", Object.keys(out).length, "distribution:", dist);
