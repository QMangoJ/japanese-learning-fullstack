const circled = "①②③④⑤⑥⑦⑧⑨⑩";

function answerSlices(source, marker) {
	const part = String(source || "").split(marker === "choice" ? "Ⅱ：" : "Ⅱ：")[marker === "choice" ? 0 : 1] || "";
	const result = {};
	for (let index = 0; index < circled.length; index += 1) {
		const symbol = circled[index];
		const start = part.indexOf(symbol);
		if (start < 0) continue;
		let end = part.length;
		for (let next = index + 1; next < circled.length; next += 1) {
			const candidate = part.indexOf(circled[next], start + 1);
			if (candidate >= 0) {
				end = candidate;
				break;
			}
		}
		result[index + 1] = part.slice(start + 1, end).replace(marker === "choice" ? /[Ⅰ：\s]/g : /^\s+|\s+$/g, "");
	}
	return result;
}

function choicePairs(question) {
	return [...String(question).matchAll(/（a\.\s*([\s\S]*?)\s+b\.\s*([\s\S]*?)）/g)].map((match) => ({ a: match[1].trim(), b: match[2].trim() }));
}

function choiceCodes(answer, pairCount) {
	const clean = String(answer || "").replace(/\s/g, "");
	if (clean.includes("、")) return clean.split("、");
	if (pairCount > 1 && /^[ab]+$/.test(clean) && clean.length === pairCount) return [...clean];
	return [clean];
}

function normalizeCompleted(value) {
	return String(value)
		.replaceAll("吸っていはいけない", "吸ってはいけない")
		.replaceAll("というのはは冗談", "というのは冗談")
		.replaceAll("\u3000", "")
		.trim();
}

function completeChoice(question, answer) {
	const pairs = choicePairs(question);
	const codes = choiceCodes(answer, pairs.length);
	let index = 0;
	return normalizeCompleted(String(question).replace(/（a\.\s*([\s\S]*?)\s+b\.\s*([\s\S]*?)）/g, (_all, a, b) => {
		const code = codes[index++] || codes.at(-1) || "a";
		return code.startsWith("b") ? b.trim() : a.trim();
	}));
}

function stripOptionNumber(value) {
	return String(value).replace(/^\s*[1-4]\s*/, "").trim();
}

function completeOrder(item, answer) {
	const options = Object.fromEntries((item.options || []).map((value, index) => [index + 1, stripOptionNumber(value)]));
	const order = String(answer || "").split("→").map(Number).filter(Boolean);
	let index = 0;
	return normalizeCompleted(String(item.q).replace(/＿{2,}/g, () => options[order[index++]] || "＿＿").replace(/\s+/g, ""));
}

const grammar = JSON.parse(await readFile(grammarPath, "utf8"));
const output = {};
let questionCount = 0;

for (const week of grammar.weeks || []) {
	for (const day of (week.days || []).filter((entry) => entry.day < 7)) {
		const key = `w${week.n}d${day.day}`;
		const translated = translations[key];
		const references = pointReferences[key];
		if (!translated) throw new Error(`Missing translation group: ${key}`);
		if (!references) throw new Error(`Missing point-reference group: ${key}`);
		const choiceAnswers = answerSlices(day.exercises?.answers, "choice");
		const orderAnswers = answerSlices(day.exercises?.answers, "order");
		const items = [];
		for (const section of day.exercises?.sections || []) {
			for (const item of section.items || []) {
				const answer = (section.type === "order" ? orderAnswers : choiceAnswers)[item.n];
				if (!answer) throw new Error(`Missing answer: ${key} #${item.n}`);
				const reference = references[items.length];
				const pointIndexes = Array.isArray(reference) ? reference : [reference];
				if (!pointIndexes.length || pointIndexes.some((index) => !Number.isInteger(index) || !day.points?.[index])) {
					throw new Error(`Invalid point reference: ${key} #${item.n}`);
				}
				items.push({
					n: item.n,
					type: section.type,
					answer,
					completed: section.type === "order" ? completeOrder(item, answer) : completeChoice(item.q, answer),
					translation: translated[items.length],
					pointIndexes,
					choices: section.type === "choice" ? choicePairs(item.q) : undefined,
				});
			}
		}
		if (translated.length !== items.length || references.length !== items.length || items.some((item) => !item.translation)) {
			throw new Error(`Translation count mismatch: ${key} (${translated.length}/${items.length})`);
		}
		output[key] = { items };
		questionCount += items.length;
	}
}

if (questionCount !== 250) throw new Error(`Expected 250 questions, received ${questionCount}`);
await writeFile(outputPath, `${JSON.stringify(output, null, 2)}\n`);
console.log(`Wrote ${questionCount} daily grammar explanations to ${outputPath}`);
