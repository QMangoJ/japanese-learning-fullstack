const CIRCLED_NUMS = "①②③④⑤⑥⑦⑧⑨⑩⑪⑫⑬⑭⑮⑯";

function parseDailyAnswers(text = "") {
	const answers = new Map();
	const re = new RegExp(`([${CIRCLED_NUMS}])(?:：)?([ab]|[1-4])`, "g");
	for (const match of text.matchAll(re)) {
		answers.set(CIRCLED_NUMS.indexOf(match[1]) + 1, match[2]);
	}
	return answers;
}

function normalizeWord(text = "") {
	return String(text)
		.replace(/[〜~〇○・\s]/g, "")
		.replace(/[（(][^）)]*[）)]/g, "")
		.replace(/^お(?=[\p{Script=Han}])/u, "")
		.replace(/^ご(?=[\p{Script=Han}])/u, "");
}

function dayKey(week, day) {
	return `w${week.n}d${day.day}`;
}

function dailyDays(book) {
	return (book.weeks || []).flatMap((week) =>
		(week.days || []).filter((day) => day.day < 7).map((day) => ({ week, day })),
	);
}

function buildVocabTranslations(vocab) {
	const output = {};
	for (const { week, day } of dailyDays(vocab)) {
		const key = dayKey(week, day);
		const items = (day.exercises?.sections || []).flatMap((section) => section.items || []);
		const translations = vocabTranslations[key];
		if (!translations || translations.length !== items.length) {
			throw new Error(`${key}: vocab translation count ${translations?.length ?? 0}/${items.length}`);
		}
		output[key] = { items: items.map((item, index) => ({ n: item.n, translation: translations[index] })) };
	}
	return output;
}

